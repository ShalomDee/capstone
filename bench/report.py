"""Summarise one measurement run into tables and charts.

Run: python3 bench/report.py bench/results/<date-time>
(scripts/run_measurements.sh calls this at the end.)

Writes docs/results/results-<env>.md and docs/results/figures/<env>/*.png|svg,
where <env> is wsl, codespaces, docker or linux, read from environment.txt.
Charts use IEEE column widths (3.5 in one column, 7.16 in two) at 600 dpi.
Owner: Shalom.
"""
import csv
import logging
import os
import re
import statistics
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
logging.getLogger("matplotlib.font_manager").setLevel(logging.ERROR)  # Segoe UI only exists on Windows
plt.rcParams["font.family"] = ["Segoe UI", "DejaVu Sans"]
plt.rcParams["svg.fonttype"] = "none"
plt.rcParams["font.size"] = 8
INK = "#111111"
BLUE = "#1f5fae"
GREEN = "#0f6e4a"
ORANGE = "#b0441a"
GREY = "#9aa3ad"
NARROW = 3.5


def pct(values, p):
    """Same positions as the C programs: sorted v[n/2], v[n/10], v[n*9/10]."""
    v = sorted(values)
    return v[int(len(v) * p)]


def ms(ns):
    return ns / 1e6


def read_env(out):
    env = {}
    with open(os.path.join(out, "environment.txt"), encoding="utf8") as f:
        for line in f:
            if ": " in line:
                k, v = line.rstrip("\n").split(": ", 1)
                env.setdefault(k, v)
    e = env.get("environment", "").lower()
    slug = "wsl" if "wsl" in e else "codespaces" if "codespaces" in e else "docker" if "docker" in e else "linux"
    return env, slug


def parse_time_pqc(out):
    ops, checks = [], []
    alg = ""
    with open(os.path.join(out, "time_pqc.txt"), encoding="utf8") as f:
        for line in f:
            m = re.match(r"(ML-\S+), (\d+) runs", line)
            if m:
                alg = m.group(1)
                continue
            m = re.match(r"(\w+)\s+median\s+([\d.]+) ms\s+p10\s+([\d.]+)\s+p90\s+([\d.]+)", line)
            if m:
                ops.append((alg, m.group(1), float(m.group(2)), float(m.group(3)), float(m.group(4))))
            elif "rejected" in line:
                checks.append(line.strip())
    return ops, checks


def parse_bench_lines(path):
    vals = {}
    with open(path, encoding="utf8") as f:
        for line in f:
            if line.startswith("BENCH,"):
                _, label, value, unit = line.strip().split(",")
                vals[label] = (int(value), unit)
    return vals


def save(fig, figdir, name):
    os.makedirs(figdir, exist_ok=True)
    for ext in ("png", "svg"):
        fig.savefig(os.path.join(figdir, f"{name}.{ext}"), dpi=600, facecolor="white", bbox_inches="tight")
    plt.close(fig)


def style(ax):
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.tick_params(colors=INK, labelsize=7.5)
    ax.grid(axis="y", color="#d9dde2", linewidth=0.5)
    ax.set_axisbelow(True)


def main(out):
    env, slug = read_env(out)
    machine = f"{env.get('cpu', '?')}, {env.get('environment', 'Linux')}, {env.get('os', '')}"
    figdir = os.path.join(ROOT, "docs", "results", "figures", slug)
    md = []
    w = md.append
    w(f"# QuantumDrive results ({slug})\n")
    w("Generated by `bench/report.py` from `make measure` (several complete runs in one sitting; section 7 shows the spread). Do not edit by hand; rerun instead.\n")
    w("| Field | Value |\n|---|---|")
    for k in ("date", "cpu", "logical cpus", "environment", "os", "kernel", "liboqs", "openssl", "gcc", "git", "securenet"):
        if k in env:
            w(f"| {k} | {env[k]} |")
    w("")

    # ---------------------------------------------------------------- liboqs
    ops, checks = parse_time_pqc(out)
    w("## 1. Post-quantum operations (liboqs, 1,000 runs each)\n")
    w("| Algorithm | Operation | Median (ms) | p10 (ms) | p90 (ms) |\n|---|---|---:|---:|---:|")
    for alg, op, med, p10, p90 in ops:
        w(f"| {alg} | {op} | {med:.4f} | {p10:.4f} | {p90:.4f} |")
    w("")
    for c in checks:
        w(f"- {c}")
    w("")

    sign = parse_bench_lines(os.path.join(out, "time_sign.txt"))
    w("## 2. Signing through our code (`id_sign`, `id_verify`, 1,000 runs)\n")
    w("`id_sign` reads the private key file on every call, so its time includes that read.\n")
    w("| Operation | Median (ms) |\n|---|---:|")
    w(f"| id_sign | {ms(sign['sign_median'][0]):.4f} |")
    w(f"| id_verify | {ms(sign['verify_median'][0]):.4f} |")
    w(f"| signature size | {sign['signature_bytes'][0]:,} B |\n")

    fig, ax = plt.subplots(figsize=(NARROW, 2.1))
    labels = [f"{a.replace('ML-', 'ML-')} {o}" for a, o, *_ in ops]
    meds = [m for *_, m, _, _ in ops]
    lo = [m - p for *_, m, p, _ in ops]
    hi = [q - m for *_, m, _, q in ops]
    y = range(len(ops))
    colors = [GREEN if a.startswith("ML-KEM") else BLUE for a, *_ in ops]
    ax.barh(list(y), [m * 1000 for m in meds], color=colors, height=0.6,
            xerr=[[v * 1000 for v in lo], [v * 1000 for v in hi]], error_kw={"elinewidth": 0.8, "capsize": 2, "ecolor": INK})
    ax.set_yticks(list(y), labels)
    ax.invert_yaxis()
    ax.set_xlabel("Median time (µs), whiskers p10 to p90")
    style(ax)
    ax.grid(axis="x", color="#d9dde2", linewidth=0.5)
    ax.grid(axis="y", visible=False)
    save(fig, figdir, "pqc_operations")

    # ---------------------------------------------------------------- sensor CPU
    rows = list(csv.DictReader(open(os.path.join(out, "sensor_cpu.csv"), encoding="utf8")))
    by = {}
    for r in rows:
        by.setdefault(int(r["batch"]), {}).setdefault(int(r["run"]), {})[r["label"]] = int(r["value"])
    w("## 3. Sensor: CPU time and memory per reading (1,000 readings, 11 runs, median)\n")
    w("CPU time covers making, writing, re-reading and checking each file, hashing it and signing it with ML-DSA-65 (user + system time). Key generation is excluded.\n")
    w("| Readings per file | CPU per reading (µs) | Wall per reading (µs) | Peak memory (KiB) |\n|---:|---:|---:|---:|")
    cpu_points = []
    for batch in sorted(by):
        runs = by[batch].values()
        cpu = statistics.median(r["cpu_ns"] / r["readings"] for r in runs) / 1e3
        wall = statistics.median(r["wall_ns"] / r["readings"] for r in runs) / 1e3
        rss = statistics.median(r["peak_rss_kib"] for r in runs)
        cpu_points.append((batch, cpu))
        w(f"| {batch} | {cpu:.1f} | {wall:.1f} | {rss:,.0f} |")
    w("")
    fig, ax = plt.subplots(figsize=(NARROW, 1.9))
    ax.bar([str(b) for b, _ in cpu_points], [c for _, c in cpu_points], color=BLUE, width=0.55)
    for i, (_, c) in enumerate(cpu_points):
        ax.text(i, c, f"{c:.1f}", ha="center", va="bottom", fontsize=7.5, color=INK)
    ax.set_xlabel("Readings per signed file")
    ax.set_ylabel("CPU time per reading (µs)")
    style(ax)
    save(fig, figdir, "sensor_cpu_per_reading")

    # ---------------------------------------------------------------- network
    net = list(csv.DictReader(open(os.path.join(out, "net.csv"), encoding="utf8")))
    for r in net:
        for k in ("ns", "c2s", "s2c", "computed_c2s", "computed_s2c", "readings", "data_bytes"):
            r[k] = int(r[k])
    mismatches = [r for r in net if r["c2s"] != r["computed_c2s"] or r["s2c"] != r["computed_s2c"]]

    hs = [r for r in net if r["kind"] == "handshake"]
    t = [r["ns"] for r in hs]
    w("## 4. Handshake over a real socket (connect + ML-KEM-768 handshake, 1,000 runs, loopback)\n")
    w("| Median (ms) | p10 (ms) | p90 (ms) | Bytes client to server | Bytes server to client |\n|---:|---:|---:|---:|---:|")
    w(f"| {ms(pct(t, 0.5)):.3f} | {ms(pct(t, 0.1)):.3f} | {ms(pct(t, 0.9)):.3f} | {hs[0]['c2s']:,} | {hs[0]['s2c']:,} |\n")

    reg = [r for r in net if r["kind"] == "register"]
    if reg:
        r = reg[0]
        w(f"Register (new connection + REGISTER + OK): {r['c2s']:,} B sent, {r['s2c']:,} B received (computed {r['computed_c2s']:,} / {r['computed_s2c']:,}).\n")

    w("## 5. Upload time over a real socket (loopback, one new connection per upload)\n")
    w("Each upload: hash and sign the record, connect, handshake, send in 64 KiB chunks, server checks size, hash and signature, stores, replies OK.\n")
    w("| File | Runs | Median (ms) | p10 (ms) | p90 (ms) | MB/s at median | Bytes sent | Overhead vs file |\n|---|---:|---:|---:|---:|---:|---:|---:|")
    up_points = []
    for name in ("1KiB", "100KiB", "1MiB", "10MiB"):
        rs = [r for r in net if r["kind"] == "upload" and r["param"] == name]
        if not rs:
            continue
        t = [r["ns"] for r in rs]
        size = rs[0]["data_bytes"]
        med = pct(t, 0.5)
        up_points.append((size, ms(med), ms(pct(t, 0.1)), ms(pct(t, 0.9))))
        over = rs[0]["c2s"] - size
        w(f"| {name} | {len(rs)} | {ms(med):.3f} | {ms(pct(t, 0.1)):.3f} | {ms(pct(t, 0.9)):.3f} | {size / (med / 1e9) / 1e6:.1f} | {rs[0]['c2s']:,} | {over:,} B ({100 * over / size:.1f}%) |")
    w("")
    hs_med = ms(pct([r["ns"] for r in hs], 0.5))
    fig, ax = plt.subplots(figsize=(NARROW, 2.1))
    xs = [p[0] for p in up_points]
    ax.errorbar(xs, [p[1] for p in up_points],
                yerr=[[p[1] - p[2] for p in up_points], [p[3] - p[1] for p in up_points]],
                color=BLUE, marker="o", markersize=3.5, linewidth=1.2, capsize=2, elinewidth=0.8, label="Upload (median, p10 to p90)")
    ax.axhline(hs_med, color=GREEN, linestyle="--", linewidth=1, label=f"Handshake alone ({hs_med:.2f} ms)")
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xticks(xs, ["1 KiB", "100 KiB", "1 MiB", "10 MiB"])
    ax.minorticks_off()
    ax.set_xlabel("File size")
    ax.set_ylabel("Time (ms)")
    ax.legend(fontsize=7, frameon=False, loc="upper left")
    style(ax)
    save(fig, figdir, "upload_time")

    w("## 6. Sensor files over a real socket: measured vs computed bytes (100 readings)\n")
    w("The client opens a new connection for every file, so each file also pays one handshake. The computed column is the one-connection model from Progress Report 2 (`make sensor-sizes`).\n")
    w("| Readings per file | Files | Sent per reading, measured (B) | Of which handshakes (B) | Upload only, measured (B) | Computed, one connection (B) | Time per reading (ms) |\n|---:|---:|---:|---:|---:|---:|---:|")
    hs_c2s = hs[0]["c2s"]
    sb_points = []
    for param in sorted({r["param"] for r in net if r["kind"] == "sensorfile"}, key=lambda p: int(p.split("-")[-1])):
        rs = [r for r in net if r["kind"] == "sensorfile" and r["param"] == param]
        readings = sum(r["readings"] for r in rs)
        sent = sum(r["c2s"] for r in rs)
        upload_only = sent - hs_c2s * len(rs)
        comp = parse_bench_lines(os.path.join(out, f"sensor_sizes_batch{param.split('-')[-1]}.txt"))
        comp_per = comp["upload_c2s_bytes"][0] / comp["readings"][0]
        data_per = comp["data_bytes"][0] / comp["readings"][0]
        t_per = ms(sum(r["ns"] for r in rs)) / readings
        sb_points.append((param.split("-")[-1], sent / readings, upload_only / readings, comp_per, data_per))
        w(f"| {param.split('-')[-1]} | {len(rs)} | {sent / readings:,.1f} | {hs_c2s * len(rs) / readings:,.1f} | {upload_only / readings:,.1f} | {comp_per:,.1f} | {t_per:.3f} |")
    w("")
    w(f"**Byte check:** {len(net) - len(mismatches)} of {len(net)} connections sent and received exactly the bytes computed from PROTOCOL.md." + ("" if not mismatches else f" Mismatches: {len(mismatches)} (see net.csv)."))
    w("")

    fig, ax = plt.subplots(figsize=(NARROW, 2.2))
    import numpy as np
    x = np.arange(len(sb_points))
    ax.bar(x - 0.2, [p[3] for p in sb_points], width=0.38, color=BLUE, label="Computed, one connection")
    ax.bar(x + 0.2, [p[1] for p in sb_points], width=0.38, color=ORANGE, label="Measured, new connection per file")
    ax.axhline(sb_points[0][4], color=INK, linestyle=":", linewidth=1, label=f"Reading data ({sb_points[0][4]:.1f} B)")
    for i, p in enumerate(sb_points):
        ax.text(i - 0.2, p[3] * 1.08, f"{p[3]:,.0f}", ha="center", va="bottom", fontsize=6.5, color=INK)
        ax.text(i + 0.2, p[1] * 1.08, f"{p[1]:,.0f}", ha="center", va="bottom", fontsize=6.5, color=INK)
    ax.set_yscale("log")
    ax.set_ylim(top=max(p[1] for p in sb_points) * 12)
    ax.set_xticks(x, [p[0] for p in sb_points])
    ax.set_xlabel("Readings per signed file")
    ax.set_ylabel("Bytes sent per reading")
    ax.legend(fontsize=6.5, frameon=False, loc="upper right")
    style(ax)
    save(fig, figdir, "sensor_bytes_per_reading")

    if len(all_runs) > 1:
        w(f"## 7. Run-to-run spread ({len(all_runs)} complete runs, same sitting)\n")
        w("Every table above comes from one representative run (the one whose ML-DSA-65 sign median is the middle value). "
          "This table shows how much each key median moved between the complete runs. Byte counts did not change between runs.\n")
        w("| Median | This run | Lowest run | Highest run |\n|---|---:|---:|---:|")
        keys = key_metrics(out)
        everyone = [key_metrics(r) for r in all_runs]
        for name, unit in METRICS:
            vals = [m[name] for m in everyone]
            w(f"| {name} ({unit}) | {keys[name]:.4g} | {min(vals):.4g} | {max(vals):.4g} |")
        w("")
        w("Runs: " + ", ".join(f"`{os.path.basename(os.path.normpath(r))}`" for r in all_runs) + "\n")

    w(f"## Figures\n\nIn `docs/results/figures/{slug}/` (PNG 600 dpi and SVG): `pqc_operations`, `sensor_cpu_per_reading`, `upload_time`, `sensor_bytes_per_reading`.\n")
    w(f"Machine for every number above: {machine}.\n")

    path = os.path.join(ROOT, "docs", "results", f"results-{slug}.md")
    with open(path, "w", encoding="utf8", newline="\n") as f:
        f.write("\n".join(md))
    print(f"wrote {os.path.relpath(path, ROOT)} and {os.path.relpath(figdir, ROOT)}/")


METRICS = [
    ("ML-KEM-768 keypair", "ms"), ("ML-KEM-768 encapsulate", "ms"), ("ML-KEM-768 decapsulate", "ms"),
    ("ML-DSA-65 sign", "ms"), ("ML-DSA-65 verify", "ms"),
    ("handshake over socket", "ms"), ("upload 1 MiB", "ms"), ("upload 10 MiB", "ms"),
    ("sensor CPU per reading, 1 per file", "µs"), ("sensor CPU per reading, 100 per file", "µs"),
]


def key_metrics(out):
    ops, _ = parse_time_pqc(out)
    m = {f"{a} {o}": med for a, o, med, _, _ in ops}
    net = list(csv.DictReader(open(os.path.join(out, "net.csv"), encoding="utf8")))
    for name, kind, param in (("handshake over socket", "handshake", "-"),
                              ("upload 1 MiB", "upload", "1MiB"), ("upload 10 MiB", "upload", "10MiB")):
        m[name] = ms(pct([int(r["ns"]) for r in net if r["kind"] == kind and r["param"] == param], 0.5))
    rows = list(csv.DictReader(open(os.path.join(out, "sensor_cpu.csv"), encoding="utf8")))
    for batch in (1, 100):
        runs = {}
        for r in rows:
            if int(r["batch"]) == batch:
                runs.setdefault(r["run"], {})[r["label"]] = int(r["value"])
        m[f"sensor CPU per reading, {batch} per file"] = statistics.median(
            r["cpu_ns"] / r["readings"] for r in runs.values()) / 1e3
    return m


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit("usage: python3 bench/report.py bench/results/<run> [<run> ...]")
    all_runs = sys.argv[1:]
    # Representative run: the one whose ML-DSA-65 sign median is the middle value.
    by_sign = sorted(all_runs, key=lambda r: key_metrics(r)["ML-DSA-65 sign"])
    main(by_sign[len(by_sign) // 2])
